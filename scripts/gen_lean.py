#!/usr/bin/env python3
"""Generate Lean 4 metadata definitions from normalized card JSON.

Writes `FabCards/<Set>/Meta.lean` containing one `CardDef` per logical card with
printed characteristics and optional card-text docstrings.
Run with `--check` (as in `scripts/verify.sh`) to verify generated files are up to date.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys


def lean_str(s: str) -> str:
    esc = (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "")
    )
    return f'"{esc}"'


def lean_docstring(card: dict) -> str:
    header = f"{card['name']} ({card['primary_print_id']} — {card['type_text']})"
    if "functional_text" not in card:
        return f"/-- {header} -/"
    text = card["functional_text"] or "(No functional text)"
    # Avoid accidental Lean comment terminators or bare CR references inside card text.
    safe_text = text.replace("/-", "/ -").replace("-/", "- /")
    lines = [header, ""] + safe_text.splitlines()
    if len(lines) == 1:
        return f"/-- {lines[0]} -/"
    body = "\n".join(lines)
    return f"/--\n{body}\n-/"


def fmt_supertype(st: dict) -> str:
    if st["kind"] == "generic":
        return ".generic"
    if st["kind"] == "class_":
        return f".class_ .{st['val']}"
    if st["kind"] == "talent":
        return f".talent .{st['val']}"
    raise ValueError(f"Unknown supertype {st}")


def fmt_keyword(kw: dict) -> str:
    if kw["kind"] == "specialization":
        return f".specialization {lean_str(kw['arg'])}"
    if kw["kind"] == "arcaneBarrier":
        return f".arcaneBarrier {kw['arg']}"
    return f".{kw['kind']}"


def fmt_opt_int(val: int | None) -> str:
    if val is None:
        return "none"
    return f"some ({val})" if val < 0 else f"some {val}"


def fmt_opt_nat(val: int | None) -> str:
    return "none" if val is None else f"some {val}"


def fmt_cost(cost: dict | None) -> str:
    if cost is None:
        return "none"
    return f"some {{ actionPoints := {cost['actionPoints']}, resources := {cost['resources']} }}"


def fmt_card_def(card: dict) -> str:
    cid = card["card_id"]
    supers = ", ".join(fmt_supertype(s) for s in card["supertypes"])
    tys = ", ".join(f".{t}" for t in card["types"])
    subs = ", ".join(f".{s}" for s in card["subtypes"])
    kws = ", ".join(fmt_keyword(k) for k in card["keywords"])
    color = "none" if card["color"] is None else f"some .{card['color']}"

    fields = [
        f"name := {lean_str(card['name'])}",
        f"supertypes := [{supers}]",
        f"types := [{tys}]",
    ]
    if subs:
        fields.append(f"subtypes := [{subs}]")
    if card["color"] is not None:
        fields.append(f"color := {color}")
    if card["pitch"] is not None:
        fields.append(f"pitch := {fmt_opt_nat(card['pitch'])}")
    if card["cost"] is not None:
        fields.append(f"cost := {fmt_cost(card['cost'])}")
    if card["power"] is not None:
        fields.append(f"power := {fmt_opt_int(card['power'])}")
    if card["defense"] is not None:
        fields.append(f"defense := {fmt_opt_int(card['defense'])}")
    if card["intellect"] is not None:
        fields.append(f"intellect := {fmt_opt_nat(card['intellect'])}")
    if card["life"] is not None:
        fields.append(f"life := {fmt_opt_int(card['life'])}")
    if kws:
        fields.append(f"keywords := [{kws}]")

    sets = ", ".join(
        f".{code.lower()}" if code in {"WTR", "ARC", "CRU", "MON"} else f"⟨{lean_str(code)}⟩"
        for code in card["sets"]
    )
    front_body = "\n        ".join(fields)
    doc = lean_docstring(card)
    return (
        f"{doc}\n"
        f"def {cid}_meta : CardDef :=\n"
        f"  {{ id := ⟨{lean_str(cid)}⟩\n"
        f"    front :=\n"
        f"      {{ {front_body} }}\n"
        f"    sets := [{sets}]\n"
        f"    status := .todo }}\n"
    )


def render_meta_module(payload: dict) -> str:
    set_code = payload["set_code"]
    commit = (payload.get("source_commit") or "unknown")[:12]
    cards = payload["cards"]

    parts = [
        "module",
        "",
        "public import Fab.Card.CardDB",
        "",
        "/-!",
        f"# Generated {set_code} card metadata",
        "",
        f"AUTO-GENERATED by `scripts/gen_lean.py` from `data/normalized/{set_code.lower()}_cards.json`",
        f"(upstream snapshot `{payload.get('source_repo')}@{commit}`, {len(cards)} logical cards).",
        f"Do not edit by hand; update handwritten IR overrides in `FabCards/{set_code}.lean` instead.",
        "-/",
        "",
        "@[expose] public section",
        "",
        f"namespace FabCards.{set_code}.Meta",
        "",
        "open Fab",
        "",
    ]

    for c in cards:
        parts.append(fmt_card_def(c))

    id_list = ",\n  ".join(f"{c['card_id']}_meta" for c in cards)
    parts.append(
        f"/-- All {len(cards)} generated {set_code} metadata card definitions. -/\n"
        f"def allMeta : List CardDef := [\n  {id_list}\n]\n"
    )
    parts.append(f"end FabCards.{set_code}.Meta\n")
    parts.append("end\n")
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--in", dest="in_path", default="data/normalized/wtr_cards.json")
    parser.add_argument("--out", dest="out_path", default="FabCards/WTR/Meta.lean")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if generated output differs from disk",
    )
    args = parser.parse_args()

    payload = json.loads(pathlib.Path(args.in_path).read_text(encoding="utf-8"))
    rendered = render_meta_module(payload)
    out_path = pathlib.Path(args.out_path)

    if args.check:
        if not out_path.exists():
            print(f"MISSING generated file: {out_path}", file=sys.stderr)
            return 1
        existing = out_path.read_text(encoding="utf-8")
        if existing != rendered:
            print(f"STALE generated file: {out_path} (run python3 scripts/gen_lean.py)", file=sys.stderr)
            return 1
        print(f"gen_lean --check: OK ({out_path}, {payload['card_count']} cards)")
        return 0

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(rendered, encoding="utf-8")
    print(f"Generated {out_path} ({payload['card_count']} cards)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
